#!/usr/bin/env bash
# Custom icons for the Firefox homepage (about:newtab / about:home).
#
#   ff-icons.sh add [--themed] <file> [name]   add an icon, rebuild
#   ff-icons.sh list                           show what is installed
#   ff-icons.sh remove <name>                  remove an icon, rebuild
#   ff-icons.sh build                          regenerate CSS and sync to Firefox
#
# <name> is the site the tile points to (github.com, youtube.com ...) or "logo"
# to replace the big Firefox logo. If omitted, the file name is used.
#
# --themed  tints the icon with your matugen primary colour (use single-colour SVGs/PNGs;
#           the shape's alpha is what counts). Without it the icon keeps its own colours,
#           so GIFs animate and multi-colour SVGs stay as they are.
#
# Sources live in ~/.config/firefox-icons/ (keep it in git). Everything is copied
# into Firefox's chrome/ folder by "build". Restart Firefox afterwards.
set -e

SRC="${FF_SRC:-$HOME/.config/firefox-icons}"
LIVE="${FF_LIVE:-$HOME/.config/mozilla/firefox/mnvwbvy5.default-release/chrome}"
EXTS="svg gif png webp jpg jpeg apng avif"

[ -d "$LIVE" ] || { echo "Firefox chrome dir not found: $LIVE"; exit 1; }
command -v python3 >/dev/null || { echo "python3 required"; exit 1; }
mkdir -p "$SRC/themed"

build() {
python3 - "$SRC" "$LIVE" <<'__PY__'
import os, re, sys, shutil, time, urllib.parse

src, live = sys.argv[1], sys.argv[2]
EXTS = {"svg", "gif", "png", "webp", "jpg", "jpeg", "apng", "avif"}

def items(d, themed):
    if not os.path.isdir(d):
        return
    for f in sorted(os.listdir(d)):
        if not os.path.isfile(os.path.join(d, f)):
            continue
        stem, _, ext = f.rpartition(".")
        if ext.lower() not in EXTS:
            continue
        if not re.fullmatch(r"[A-Za-z0-9.-]+", stem):
            print("  skipping (bad name):", f)
            continue
        yield stem, f, themed

out = []
n = 0
for d, themed in ((src, False), (os.path.join(src, "themed"), True)):
    for stem, f, themed in items(d, themed):
        n += 1
        rel = "icons/" + ("themed/" if themed else "") + urllib.parse.quote(f)
        if stem == "logo":
            sel = ".logo-and-wordmark .logo"
            if themed:
                out.append(f"""  {sel} {{
    background-image: none !important;
    background-color: var(--primary) !important;
    -webkit-mask: url("{rel}") center / contain no-repeat !important;
    mask: url("{rel}") center / contain no-repeat !important;
  }}""")
            else:
                out.append(f"""  {sel} {{
    background-image: url("{rel}") !important;
    background-size: contain !important;
    background-repeat: no-repeat !important;
    background-position: center !important;
  }}""")
            continue

        a = f'.top-site-outer a[href*="{stem}"]'
        if themed:
            out.append(f"""  {a} .tile {{ position: relative !important; }}
  {a} .tile > * {{ opacity: 0 !important; }}
  {a} .tile::after {{
    content: "";
    position: absolute;
    inset: 0;
    background-color: var(--primary);
    -webkit-mask: url("{rel}") center / 58% no-repeat;
    mask: url("{rel}") center / 58% no-repeat;
    transition: background-color 0.15s;
  }}
  .top-site-outer:hover {a} .tile::after {{ background-color: var(--on_primary); }}""")
        else:
            out.append(f"""  {a} .tile {{
    background-image: url("{rel}") !important;
    background-size: 58% !important;
    background-repeat: no-repeat !important;
    background-position: center !important;
  }}
  {a} .tile > * {{ opacity: 0 !important; }}""")

css = "/* generated by ff-icons.sh - do not edit */\n"
if out:
    css += '@-moz-document url("about:home"), url("about:newtab"), url("about:privatebrowsing") {\n'
    css += "\n".join(out) + "\n}\n"
open(os.path.join(live, "icons.css"), "w").write(css)

# sync icon files into Firefox's chrome folder (copy, not symlink: content processes
# are sandboxed and may not follow links out of the profile)
dst = os.path.join(live, "icons")
if os.path.isdir(dst):
    shutil.rmtree(dst)
shutil.copytree(src, dst)

uc = os.path.join(live, "userContent.css")
if os.path.exists(uc):
    s = open(uc).read()
    if '@import "icons.css"' not in s:
        shutil.copy(uc, os.path.expanduser("~/userContent.css.bak-icons-%d" % int(time.time())))
        m = re.search(r'@import\s+["\']colors\.css["\'];[^\n]*\n', s)
        line = '@import "icons.css";\n'
        s = (s[:m.end()] + line + s[m.end():]) if m else (line + s)
        open(uc, "w").write(s)   # writes through symlinks, keeps the link
        print("Added @import \"icons.css\" to userContent.css")
else:
    print("WARNING: userContent.css not found in", live)

print("Built %d icon rule(s) -> %s" % (n, os.path.join(live, "icons.css")))
__PY__
echo "Restart Firefox, then open a new tab."
}

add() {
    local themed=0
    if [ "$1" = "--themed" ]; then themed=1; shift; fi
    local f="$1" name="$2"
    [ -n "$f" ] && [ -f "$f" ] || { echo "file not found: $f"; exit 1; }
    local base ext stem dest
    base="$(basename "$f")"
    ext="$(echo "${base##*.}" | tr 'A-Z' 'a-z')"
    stem="${base%.*}"
    [ -n "$name" ] && stem="$name"
    case " $EXTS " in *" $ext "*) ;; *) echo "unsupported type .$ext (use: $EXTS)"; exit 1;; esac
    case "$stem" in ''|*[!A-Za-z0-9.-]*) echo "name must be a domain like github.com (letters, numbers, dots, dashes) or 'logo'"; exit 1;; esac
    dest="$SRC"; [ "$themed" = 1 ] && dest="$SRC/themed"
    for d in "$SRC" "$SRC/themed"; do for e in $EXTS; do rm -f "$d/$stem.$e"; done; done
    cp "$f" "$dest/$stem.$ext"
    echo "Added $stem.$ext ($([ "$themed" = 1 ] && echo themed || echo full-colour))"
    build
}

list() {
    echo "Full-colour:"; ls -1 "$SRC" 2>/dev/null | grep -v '^themed$' | sed 's/^/  /' || true
    echo "Themed (matugen tinted):"; ls -1 "$SRC/themed" 2>/dev/null | sed 's/^/  /' || true
}

remove() {
    [ -n "$1" ] || { echo "usage: remove <name>"; exit 1; }
    for d in "$SRC" "$SRC/themed"; do for e in $EXTS; do rm -f "$d/$1.$e"; done; done
    echo "Removed $1"
    build
}

cmd="${1:-help}"; shift || true
case "$cmd" in
    add)    add "$@" ;;
    list)   list ;;
    remove) remove "$@" ;;
    build)  build ;;
    *)      sed -n '2,17p' "$0" ;;
esac
